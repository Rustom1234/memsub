"""Error analysis for the LOCOMO dev split: WHY does evidence recall fail?

For every dev question (conversations 1-3, categories 1-4) at a given budget,
attribute the outcome to one of:

  ok                all evidence turns packed
  evidence_missing  an annotated evidence dia_id has no matching stored turn
                    (ingestion/annotation gap, our analog of never-extracted)
  budget_cut        every evidence turn ranked inside the packable prefix,
                    but at least one was skipped for size / budget
  ranked_low        at least one evidence turn ranked below what the budget
                    could ever include (retrieval miss)

Also computes an oracle bound: pack evidence turns first (perfect ranking),
same budget; questions whose evidence cannot fit even then are unfixable by
retrieval alone (they need extraction/summarization to compress evidence).

Writes docs/error-analysis-locomo.md. Dev split ONLY (holdout untouched).
"""

from __future__ import annotations

import sys
import time
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from memsub.bench import PolicySystem, load_locomo, pack_greedy  # noqa: E402
from memsub.policy import approx_tokens  # noqa: E402

BUDGET = 1000
# tuned params from the milestone-4 dev sweep (results/benchmark.json)
PARAMS = {"recency_weight": 0.999, "recency_floor": 0.75, "importance_floor": 0.0}
CATEGORY_NAMES = {1: "multi-hop", 2: "temporal", 3: "open-domain", 4: "single-hop"}


def main() -> int:
    convs = load_locomo(ROOT / "data" / "locomo10.json")[:3]  # dev split
    counts: dict[int, dict[str, int]] = defaultdict(lambda: defaultdict(int))
    sim_fail: dict[int, list[float]] = defaultdict(list)
    sim_ok: dict[int, list[float]] = defaultdict(list)
    ranks_of_failures: list[int] = []
    n_eps_total = 0

    for conv in convs:
        system = PolicySystem(**PARAMS)
        system.ingest(list(conv.episodes))
        eps = system._index.episodes
        n_eps_total += len(eps)
        id_to_pos = {ep.id: i for i, ep in enumerate(eps)}

        for q in conv.qa:
            if q.category not in CATEGORY_NAMES or not q.evidence:
                continue
            cat = q.category
            ev_ids = [f"{conv.conversation_id}:{e}" for e in q.evidence]
            missing = [e for e in ev_ids if e not in id_to_pos]
            counts[cat]["n"] += 1

            if missing:
                counts[cat]["evidence_missing"] += 1
                continue

            sims = system._index.scores(q.question)
            n = len(eps)
            arange = np.arange(n - 1, -1, -1, dtype=np.float64)
            recency = PARAMS["recency_floor"] + (1 - PARAMS["recency_floor"]) * PARAMS["recency_weight"] ** arange
            imp = np.array([ep.importance for ep in eps])
            scores = sims * recency * imp
            order = list(np.argsort(-scores, kind="stable"))
            rank_of = {int(pos): r for r, pos in enumerate(order)}

            packed = pack_greedy([eps[i] for i in order], BUDGET)
            packed_ids = {ep.id for ep in packed}
            packed_count = len(packed)

            ev_sims = [float(sims[id_to_pos[e]]) for e in ev_ids]
            if all(e in packed_ids for e in ev_ids):
                counts[cat]["ok"] += 1
                sim_ok[cat].extend(ev_sims)
                continue

            sim_fail[cat].extend(ev_sims)
            worst_rank = max(rank_of[id_to_pos[e]] for e in ev_ids if e not in packed_ids)
            ranks_of_failures.append(worst_rank)
            if worst_rank < packed_count:
                counts[cat]["budget_cut"] += 1
            else:
                counts[cat]["ranked_low"] += 1

            # oracle: would perfect ranking fit the evidence under the budget?
            ev_eps = [eps[id_to_pos[e]] for e in ev_ids]
            ev_cost = sum(approx_tokens(ep.content) + 1 for ep in ev_eps)
            if ev_cost > BUDGET:
                counts[cat]["oracle_unfixable"] += 1

    # ---- report ------------------------------------------------------------- #
    lines = [
        "# LOCOMO dev-split error analysis (evidence-all at budget 1000)",
        "",
        f"Generated by `scripts/error_analysis.py` on {time.strftime('%Y-%m-%d %H:%M')}. "
        f"Dev split: 3 conversations, {n_eps_total} stored turns total, tuned policy params {PARAMS}. "
        "Failure causes: `evidence_missing` (annotated evidence turn absent from the store), "
        "`budget_cut` (all evidence ranked inside the packable prefix but skipped for size), "
        "`ranked_low` (at least one evidence turn ranked below anything the budget could include: a retrieval miss). "
        "`oracle_unfixable` counts questions whose raw evidence exceeds the budget even with perfect ranking.",
        "",
        "| category | n | ok | evidence_missing | budget_cut | ranked_low | oracle_unfixable | fail rate |",
        "|---|---|---|---|---|---|---|---|",
    ]
    totals: dict[str, int] = defaultdict(int)
    for cat in sorted(CATEGORY_NAMES):
        c = counts[cat]
        for k, v in c.items():
            totals[k] += v
        fail = c["n"] - c["ok"]
        lines.append(
            f"| {CATEGORY_NAMES[cat]} | {c['n']} | {c['ok']} | {c['evidence_missing']} | "
            f"{c['budget_cut']} | {c['ranked_low']} | {c['oracle_unfixable']} | "
            f"{100 * fail / c['n']:.1f}% |"
        )
    fail_t = totals["n"] - totals["ok"]
    lines.append(
        f"| TOTAL | {totals['n']} | {totals['ok']} | {totals['evidence_missing']} | "
        f"{totals['budget_cut']} | {totals['ranked_low']} | {totals['oracle_unfixable']} | "
        f"{100 * fail_t / totals['n']:.1f}% |"
    )

    lines += ["", "## Similarity diagnostics (is the embedder finding evidence at all?)", ""]
    lines.append("| category | mean cosine(query, evidence) on OK | on FAIL |")
    lines.append("|---|---|---|")
    for cat in sorted(CATEGORY_NAMES):
        mo = float(np.mean(sim_ok[cat])) if sim_ok[cat] else float("nan")
        mf = float(np.mean(sim_fail[cat])) if sim_fail[cat] else float("nan")
        lines.append(f"| {CATEGORY_NAMES[cat]} | {mo:.3f} | {mf:.3f} |")

    if ranks_of_failures:
        r = np.array(ranks_of_failures)
        lines += [
            "",
            f"Worst evidence rank on failures: median {int(np.median(r))}, "
            f"p75 {int(np.percentile(r, 75))}, max {int(r.max())} "
            f"(a 1000-token budget packs roughly the top 45-60 turns).",
        ]

    out = ROOT / "docs" / "error-analysis-locomo.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")
    print("\n".join(lines[5:14]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
