"""LOCOMO holdout J-score run with a FRONTIER answerer (Sonnet via the local
`claude` CLI, Rustom's Max plan subscription, never an API key), so memsub's
number lands on the same measurement axis as the competitor numbers quoted in
docs/improvement-plan-2026-07-17.md Part A (mem0/Zep/Dakera/MIRIX all use a
GPT-4o-mini/4.1-mini-class frontier answerer, not an 8B local model).

Ordered directly by Rustom: "i need to beat current top locomo score also" /
"yes u can use a better model if need be (dont use api, use from my
subscription)". Reuses this repo's own machinery unchanged:
scripts/locomo_jscore_holdout.py and scripts/locomo_jscore_graph_2026-07-18.py
for the slice, sampling, system-building, and judge protocol.

Same n=80 LOCOMO holdout slice as both prior J-score runs
(scripts/holdout_answer_quality.py's holdout_convs()/sample(), conversations
4-10, random.Random(123), up to 20 questions per category). Three conditions,
run independently via --condition so each can be completed and committed
before the next starts:

  graph_decompose   memsub's best config (docs/graph-layer-2026-07-18.md):
                     HybridSystem + rank_decomposed_graph. The one bounded
                     decompose LLM call inside rank_decomposed_graph stays on
                     the LOCAL qwen3:8b backend (not Sonnet) so retrieval is
                     unchanged from the prior local-answerer runs -- only the
                     final answer-generation call switches to Sonnet. This
                     isolates the answerer change per the task's instruction.
  naive_topk        cosine top-k only, no policy -- control showing how much
                     of any gain is memsub vs. the model.
  no_memory         no retrieved context -- floor.

Per question: the answer is generated by Sonnet via ClaudeCLIBackend
(`claude -p --model sonnet`, subscription, no API key), same ANSWER_SYSTEM
prompt and same "CONTEXT:\\n...\\n\\nQUESTION: ..." structure as every local-
answerer run in this repo, budget 1000 (same greedy-packed context). Judge is
also Sonnet via ClaudeCLIBackend, blind (memsub.judge.judge_answer sees only
question/gold/answer, never the condition name), same judge prompt as the
prior two J-score runs.

Both the answer and judge `claude` CLI calls are wrapped in a retrying
backend (exponential backoff, base 15s, cap 300s, 6 attempts) so a transient
CLI rate-limit or hiccup does not lose a question -- it retries, and if it
still fails after 6 attempts the question is recorded with judge_status
"answer_error" or "error" (never guessed) and is retried automatically on the
next run since only judge_status=="ok" records are treated as done.

Streams one JSONL record per (condition, question) to
results/locomo-jscore-frontier-2026-07-18.jsonl, flushed immediately after
every record. Resumable: an (condition, conversation_id, question) key
already recorded with judge_status "ok" is skipped on restart.

Usage:
  .venv/bin/python scripts/locomo_jscore_frontier_2026-07-18.py --condition graph_decompose [--limit N]
  .venv/bin/python scripts/locomo_jscore_frontier_2026-07-18.py --condition naive_topk
  .venv/bin/python scripts/locomo_jscore_frontier_2026-07-18.py --condition no_memory
"""

from __future__ import annotations

import json
import sys
import time
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from scripts.holdout_answer_quality import holdout_convs, sample  # noqa: E402
from scripts.metrics_local import ANSWER_SYSTEM, BUDGET, CATS, FROZEN  # noqa: E402

from memsub.backends import ClaudeCLIBackend, OllamaBackend  # noqa: E402
from memsub.bench import HybridSystem, NaiveTopKSystem, pack_greedy  # noqa: E402
from memsub.graph import graph_store  # noqa: E402
from memsub.judge import judge_answer  # noqa: E402
from memsub.store import EpisodicStore  # noqa: E402

RESULTS_PATH = ROOT / "results" / "locomo-jscore-frontier-2026-07-18.jsonl"
CONDITIONS = ["graph_decompose", "naive_topk", "no_memory"]  # priority order
MAX_WALL_SECONDS = 3 * 3600  # generous, per-invocation (one condition per run)


class RetryingBackend:
    """Wraps any LLMBackend's complete() with exponential backoff so a
    transient claude-CLI rate-limit or hiccup does not lose a question.
    Raises only after exhausting all attempts; callers decide how to record
    a permanent failure (never guessed at)."""

    def __init__(self, inner, max_retries: int = 6, base_delay: float = 15.0, label: str = "") -> None:
        self.name = inner.name
        self.model = inner.model
        self._inner = inner
        self._max_retries = max_retries
        self._base_delay = base_delay
        self._label = label

    def complete(self, system: str, messages: list[dict[str, str]]) -> str:
        delay = self._base_delay
        last_exc: Exception | None = None
        for attempt in range(1, self._max_retries + 1):
            try:
                return self._inner.complete(system, messages)
            except Exception as exc:  # noqa: BLE001 - retry on anything, then re-raise
                last_exc = exc
                if attempt == self._max_retries:
                    break
                print(
                    f"  [retry] {self._label} attempt {attempt}/{self._max_retries} "
                    f"failed: {str(exc)[:200]}; sleeping {delay:.0f}s",
                    flush=True,
                )
                time.sleep(delay)
                delay = min(delay * 2, 300.0)
        raise RuntimeError(f"{self._label} failed after {self._max_retries} attempts: {last_exc}") from last_exc


def _load_existing_ok_keys() -> set[tuple]:
    if not RESULTS_PATH.exists():
        return set()
    keys = set()
    for line in RESULTS_PATH.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        if rec.get("record_type") == "question" and rec.get("judge_status") == "ok":
            keys.add((rec["condition"], rec["conversation_id"], rec["question"]))
    return keys


def _all_question_records(condition: str) -> list[dict]:
    if not RESULTS_PATH.exists():
        return []
    out = []
    for line in RESULTS_PATH.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        rec = json.loads(line)
        if rec.get("record_type") == "question" and rec.get("condition") == condition:
            out.append(rec)
    return out


def _write(fh, record: dict) -> None:
    fh.write(json.dumps(record) + "\n")
    fh.flush()


def _build_system(condition: str, conv):
    """Returns (system, store). store is only non-None for graph_decompose
    (needed by rank_decomposed_graph's entity lookups)."""
    if condition == "no_memory":
        return None, None
    if condition == "naive_topk":
        s = NaiveTopKSystem()
        s.ingest(list(conv.episodes))
        return s, None
    # graph_decompose: same construction as scripts/locomo_jscore_graph_2026-07-18.py
    system = HybridSystem(**FROZEN)
    store = EpisodicStore(":memory:")
    written = [store.append(ep) for ep in conv.episodes]
    graph_store(store)
    system.ingest(written)
    return system, store


def _context_for(condition: str, system, store, question: str, decompose_backend) -> str:
    if system is None:
        return ""
    if condition == "naive_topk":
        packed = system.inject(question, BUDGET)
    else:  # graph_decompose
        order = system.rank_decomposed_graph(question, decompose_backend, store, max_subqueries=2)
        packed = pack_greedy([system.episodes[i] for i in order], BUDGET)
    return "\n".join(ep.content for ep in packed)


def run_condition(condition: str, limit: int | None) -> int:
    assert condition in CONDITIONS, condition

    # Retrieval/decomposition stays local (qwen3:8b) -- only the answerer
    # changes to Sonnet, so this run isolates the answerer variable.
    decompose_backend = OllamaBackend(model="qwen3:8b")
    answer_backend = RetryingBackend(
        ClaudeCLIBackend(model="sonnet", timeout=300), label=f"answer[{condition}]"
    )
    judge_backend = RetryingBackend(
        ClaudeCLIBackend(model="sonnet", timeout=180), label=f"judge[{condition}]"
    )

    convs = holdout_convs()
    picked = sample(convs)
    if limit is not None:
        picked = picked[:limit]

    existing = _load_existing_ok_keys()
    t0 = time.time()
    truncated = False

    RESULTS_PATH.parent.mkdir(parents=True, exist_ok=True)
    with RESULTS_PATH.open("a", encoding="utf-8") as fh:
        systems: dict[int, tuple] = {}
        for ci, qi in picked:
            conv = convs[ci]
            q = conv.qa[qi]
            key = (condition, conv.conversation_id, q.question)
            if key in existing:
                continue
            if time.time() - t0 > MAX_WALL_SECONDS:
                truncated = True
                break

            if ci not in systems:
                systems[ci] = _build_system(condition, conv)
            system, store = systems[ci]

            ctx = _context_for(condition, system, store, q.question, decompose_backend)
            prompt = f"CONTEXT:\n{ctx}\n\nQUESTION: {q.question}"

            t1 = time.perf_counter()
            try:
                answer = answer_backend.complete(ANSWER_SYSTEM, [{"role": "user", "content": prompt}])
            except Exception as exc:  # noqa: BLE001 - never crash the run on one bad question
                record = {
                    "record_type": "question",
                    "condition": condition,
                    "conversation_id": conv.conversation_id,
                    "category": q.category,
                    "category_name": CATS[q.category],
                    "question": q.question,
                    "gold": q.answer,
                    "answer": None,
                    "correct": None,
                    "judge_status": "answer_error",
                    "answer_error": str(exc)[:300],
                    "answer_latency_s": round(time.perf_counter() - t1, 3),
                    "judge_latency_s": None,
                }
                _write(fh, record)
                print(f"  [{condition}] {conv.conversation_id} ANSWER FAILED: {str(exc)[:150]}", flush=True)
                continue
            answer_latency = time.perf_counter() - t1

            t2 = time.perf_counter()
            verdict = judge_answer(q.question, q.answer, answer, judge_backend)
            judge_latency = time.perf_counter() - t2

            record = {
                "record_type": "question",
                "condition": condition,
                "conversation_id": conv.conversation_id,
                "category": q.category,
                "category_name": CATS[q.category],
                "question": q.question,
                "gold": q.answer,
                "answer": answer,
                "correct": verdict["correct"],
                "judge_status": verdict["status"],
                "answer_latency_s": round(answer_latency, 3),
                "judge_latency_s": round(judge_latency, 3),
            }
            _write(fh, record)
            print(
                f"  [{condition}] {conv.conversation_id} cat={CATS[q.category]} "
                f"correct={verdict['correct']} status={verdict['status']} "
                f"({time.time() - t0:.0f}s)",
                flush=True,
            )

        for system, store in systems.values():
            if store is not None:
                store.close()

        if truncated:
            print("WALL-CLOCK CAP HIT: remaining questions skipped.")

        rows = [r for r in _all_question_records(condition) if r["judge_status"] == "ok"]
        n = len(rows)
        by_cat = {}
        for cat, name in CATS.items():
            cat_rows = [r for r in rows if r["category"] == cat]
            if cat_rows:
                by_cat[name] = {
                    "n": len(cat_rows),
                    "accuracy": round(mean(r["correct"] for r in cat_rows), 4),
                }
        summary = {
            "record_type": "summary",
            "condition": condition,
            "n_ok": n,
            "n_total_records": len(_all_question_records(condition)),
            "accuracy": round(mean(r["correct"] for r in rows), 4) if rows else None,
            "by_category": by_cat,
            "mean_answer_latency_s": round(mean(r["answer_latency_s"] for r in rows), 3) if rows else None,
            "mean_judge_latency_s": round(mean(r["judge_latency_s"] for r in rows), 3) if rows else None,
            "truncated": truncated,
        }
        _write(fh, summary)
        print(f"== {condition} done: n_ok={n} accuracy={summary['accuracy']} "
              f"({time.time() - t0:.0f}s elapsed) ==", flush=True)

    print(f"\nwrote {RESULTS_PATH}, wall {time.time() - t0:.1f}s, truncated={truncated}")
    return 1 if truncated else 0


def main() -> int:
    args = sys.argv[1:]
    if "--condition" not in args:
        print(__doc__)
        return 1
    condition = args[args.index("--condition") + 1]
    limit = None
    if "--limit" in args:
        limit = int(args[args.index("--limit") + 1])
    return run_condition(condition, limit)


if __name__ == "__main__":
    sys.exit(main())
